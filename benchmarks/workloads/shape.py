#!/usr/bin/env python3
"""shape.py — the single source of shape truth for the three-language
workload triplets (PLAN row 18).

The community benchmark report (v0.1.0) manufactured an 8× "alloc gap" by
comparing UNMATCHED queue shapes; its matched-shape control dissolved the
gap into parity. This generator makes that control the DEFAULT: the Go,
Rust, and Hybrid workload programs are all EMITTED from the one shape
definition below — same window count, same item counts, same batch/queue
structure, same windowed-mean timing (one timer per window, never per call)
— so the triplets share shapes BY CONSTRUCTION, not by discipline.

Usage:
    python3 shape.py           # regenerate go/, rust/, hy/
    python3 shape.py --check   # exit 1 if any generated file drifted

Run the triplet: ./run.sh (builds Go via the runtime module, Rust via
cargo, Hybrid via hyb check+build — the checker runs on every .hy workload).
"""

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
CSV_HEADER = "lang,workload,p50_ns,p99_ns,mean_ns,n"

# ---------------------------------------------------------------- shape ---
WINDOWS = 100          # timed windows per workload
LOAD_ITEMS = 2000      # string-processing items per window
ALLOC_BATCHES = 32     # queue batches per window
ALLOC_BATCH = 128      # items per batch (the queue shape)
ALLOC_ITEM = 960       # bytes appended per item (the report's 960B payload)
ALPHABET = list(range(1, 65))  # 64 fill bytes, indexed by (i+j)%64

GO_TEMPLATE = '''// GENERATED by shape.py — do not edit; the shape lives in shape.py.
// The Go twin of the load/alloc workload triplet (row 18: shapes shared by
// construction; windowed means via the runtime's hybench histogram).
package main

import (
	"fmt"
	"strings"
	"time"

	"hybrid.program/hybench"
)

var alphabet = []int{@ALPHABET_GO@}

func buildCorpus() []string {
	tpl := []string{
		"the quick brown fox jumps over the lazy dog",
		"hybrid emits plain go and the checker classifies the boundary",
		"a string with  several  double  spaces to split",
		"queue shapes must match across languages or the gap is fake",
	}
	items := make([]string, 0, @LOAD_ITEMS@)
	for i := 0; i < @LOAD_ITEMS@; i++ {
		items = append(items, fmt.Sprintf("%s %d %d", tpl[i%len(tpl)], i, i*7))
	}
	return items
}

func loadOnce(items []string) (tokens int, chars int) {
	for _, it := range items {
		parts := strings.Split(it, " ")
		tokens += len(parts)
		chars += len(it)
	}
	return
}

func pct(sorted []int64, p int) int64 {
	n := len(sorted)
	idx := (p*n+99)/100 - 1
	if idx < 0 {
		idx = 0
	}
	if idx >= n {
		idx = n - 1
	}
	return sorted[idx]
}

func loadWorkload() {
	items := buildCorpus()
	h := hybench.New()
	for w := 0; w < @WINDOWS@; w++ {
		t0 := time.Now()
		loadOnce(items)
		h.Record(time.Since(t0).Nanoseconds() / @LOAD_ITEMS@)
	}
	fmt.Printf("load p50=%dns p99=%dns mean=%.1fns n=%d\\n", h.P50(), h.P99(), h.Mean(), h.Count())
}

func allocWorkload() {
	h := hybench.New()
	for w := 0; w < @WINDOWS@; w++ {
		t0 := time.Now()
		for b := 0; b < @ALLOC_BATCHES@; b++ {
			for j := 0; j < @ALLOC_BATCH@; j++ {
				item := []byte{}
				for k := 0; k < @ALLOC_ITEM@; k++ {
					item = append(item, byte(alphabet[(j+k)%len(alphabet)]))
				}
				_ = item
			}
		}
		h.Record(time.Since(t0).Nanoseconds() / (@ALLOC_BATCHES@ * @ALLOC_BATCH@))
	}
	fmt.Printf("alloc p50=%dns p99=%dns mean=%.1fns n=%d\\n", h.P50(), h.P99(), h.Mean(), h.Count())
}

func main() {
	allocWorkload()
	loadWorkload()
}
'''

RUST_TEMPLATE = '''// GENERATED by shape.py — do not edit; the shape lives in shape.py.
// The Rust twin of the load/alloc workload triplet (row 18): the SAME
// window count, item counts, batch structure, and windowed-mean timing.
fn build_corpus() -> Vec<String> {
    let tpl = [
        "the quick brown fox jumps over the lazy dog",
        "hybrid emits plain go and the checker classifies the boundary",
        "a string with  several  double  spaces to split",
        "queue shapes must match across languages or the gap is fake",
    ];
    let mut items = Vec::with_capacity(@LOAD_ITEMS@);
    for i in 0..@LOAD_ITEMS@ {
        items.push(format!("{} {} {}", tpl[i % tpl.len()], i, i * 7));
    }
    items
}

fn split_ws(s: &str) -> Vec<&str> {
    s.split(' ').collect()
}

fn pct(sorted: &[i64], p: usize) -> i64 {
    let n = sorted.len();
    let rank = (p * n + 99) / 100;
    let mut idx = if rank > 0 { (p * n + 99) / 100 - 1 } else { 0 };
    if idx >= n {
        idx = n - 1;
    }
    sorted[idx]
}

fn main() {
    let alphabet: Vec<u8> = vec![@ALPHABET_RS@];

    // alloc — the SAME queue shape: @ALLOC_BATCHES@ batches x @ALLOC_BATCH@ items x @ALLOC_ITEM@ bytes.
    let mut alloc_means: Vec<i64> = Vec::with_capacity(@WINDOWS@);
    for _ in 0..@WINDOWS@ {
        let t0 = std::time::Instant::now();
        for _b in 0..@ALLOC_BATCHES@ {
            for j in 0..@ALLOC_BATCH@ {
                let mut item: Vec<u8> = Vec::new();
                for k in 0..@ALLOC_ITEM@ {
                    item.push(alphabet[(j + k) % alphabet.len()]);
                }
                std::hint::black_box(&item);
            }
        }
        alloc_means.push(t0.elapsed().as_nanos() as i64 / (@ALLOC_BATCHES@ * @ALLOC_BATCH@));
    }
    alloc_means.sort_unstable();
    println!(
        "alloc p50={}ns p99={}ns mean={:.1}ns n={}",
        pct(&alloc_means, 50),
        pct(&alloc_means, 99),
        alloc_means.iter().sum::<i64>() as f64 / alloc_means.len() as f64,
        alloc_means.len()
    );

    // load — the SAME corpus + split + count shape.
    let items = build_corpus();
    let mut load_means: Vec<i64> = Vec::with_capacity(@WINDOWS@);
    for _ in 0..@WINDOWS@ {
        let t0 = std::time::Instant::now();
        let mut tokens = 0usize;
        let mut chars = 0usize;
        for it in &items {
            tokens += split_ws(it).len();
            chars += it.len();
        }
        std::hint::black_box((tokens, chars));
        load_means.push(t0.elapsed().as_nanos() as i64 / @LOAD_ITEMS@);
    }
    load_means.sort_unstable();
    println!(
        "load p50={}ns p99={}ns mean={:.1}ns n={}",
        pct(&load_means, 50),
        pct(&load_means, 99),
        load_means.iter().sum::<i64>() as f64 / load_means.len() as f64,
        load_means.len()
    );
}
'''

HY_LOAD_TEMPLATE = '''// GENERATED by shape.py — do not edit; the shape lives in shape.py.
// The Hybrid load workload — the checker runs on every build (hyb check is
// part of run.sh), so this file is also a checker exercise at realistic
// scale. Same windows, same items, same windowed-mean timing as the Go and
// Rust twins (row 18: shapes shared by construction).

const windows = @WINDOWS@
const load_items = @LOAD_ITEMS@

fn split_count(s string) int {
    parts := strings.split(s, " ")
    return len(parts)
}

fn pct(a []int, p int) int {
    sorted := append([]int{}, a...)
    for i in 1..len(sorted) {
        v := sorted[i]
        j := i - 1
        for j >= 0 && sorted[j] > v {
            sorted[j+1] = sorted[j]
            j--
        }
        sorted[j+1] = v
    }
    n := len(sorted)
    idx := (p * n + 99) / 100 - 1
    if idx < 0 {
        idx = 0
    }
    if idx >= n {
        idx = n - 1
    }
    return sorted[idx]
}

fn main() {
    tpl := []string{
        "the quick brown fox jumps over the lazy dog",
        "hybrid emits plain go and the checker classifies the boundary",
        "a string with  several  double  spaces to split",
        "queue shapes must match across languages or the gap is fake",
    }
    items := []string{}
    for i in 0..load_items {
        items = append(items, fmt.sprintf("%s %d %d", tpl[i%len(tpl)], i, i*7))
    }

    means := []int{}
    total := 0
    for w in 0..windows {
        t0 := time.now()
        tokens := 0
        chars := 0
        for it in items {
            tokens += split_count(it)
            chars += len(it)
        }
        dt := time.since(t0)
        ns := int(dt.nanoseconds / load_items)
        means = append(means, ns)
        total += tokens + chars
    }
    _ = total
    fmt.println("load p50={pct(means, 50)}ns p99={pct(means, 99)}ns mean={sum_means(means)}ns n={len(means)}")
}

fn sum_means(a []int) int {
    s := 0
    for v in a {
        s += v
    }
    return s / len(a)
}
'''

HY_ALLOC_TEMPLATE = '''// GENERATED by shape.py — do not edit; the shape lives in shape.py.
// The Hybrid alloc workload — the SAME queue shape as the Go and Rust
// twins: @ALLOC_BATCHES@ batches x @ALLOC_BATCH@ items x @ALLOC_ITEM@ appended bytes per window,
// windowed means (one timer per window — the timer-honesty rule).

const windows = @WINDOWS@
const batches = @ALLOC_BATCHES@
const batch = @ALLOC_BATCH@
const item_len = @ALLOC_ITEM@

fn alphabet() []byte {
    return []byte{@ALPHABET_HY@}
}

fn pct(a []int, p int) int {
    sorted := append([]int{}, a...)
    for i in 1..len(sorted) {
        v := sorted[i]
        j := i - 1
        for j >= 0 && sorted[j] > v {
            sorted[j+1] = sorted[j]
            j--
        }
        sorted[j+1] = v
    }
    n := len(sorted)
    idx := (p * n + 99) / 100 - 1
    if idx < 0 {
        idx = 0
    }
    if idx >= n {
        idx = n - 1
    }
    return sorted[idx]
}

fn sum_means(a []int) int {
    s := 0
    for v in a {
        s += v
    }
    return s / len(a)
}

fn main() {
    means := []int{}
    alphabet_values := alphabet()
    for w in 0..windows {
        t0 := time.now()
        for b in 0..batches {
            for j in 0..batch {
                item := []byte{}
                for k in 0..item_len {
                    item = append(item, alphabet_values[(j+k)%len(alphabet_values)])
                }
                _ = item
            }
        }
        dt := time.since(t0)
        means = append(means, int(dt.nanoseconds / (batches * batch)))
    }
    fmt.println("alloc p50={pct(means, 50)}ns p99={pct(means, 99)}ns mean={sum_means(means)}ns n={len(means)}")
}
'''


def validate_iterations(iterations: int) -> int:
    if isinstance(iterations, bool) or not isinstance(iterations, int) or iterations <= 0:
        raise ValueError(f"iterations must be a positive integer (> 0), got {iterations!r}")
    return iterations


def quantile_index(n: int, p: int) -> int:
    validate_iterations(n)
    if isinstance(p, bool) or not isinstance(p, int) or p < 0 or p > 100:
        raise ValueError(f"percentile p must be in 0..100, got {p!r}")
    idx = (p * n + 99) // 100 - 1
    if idx < 0:
        idx = 0
    if idx >= n:
        idx = n - 1
    return idx


def pct_value(samples: list[int], p: int) -> int:
    ordered = sorted(samples)
    return ordered[quantile_index(len(ordered), p)]


WORKLOAD_LINE_RE = re.compile(
    r"^(alloc|load)\s+p50=(\d+)ns\s+p99=(\d+)ns\s+mean=([0-9]+(?:\.[0-9]+)?)ns\s+n=(\d+)\s*$"
)


def parse_workload_line(lang: str, line: str) -> str | None:
    m = WORKLOAD_LINE_RE.match(line.strip())
    if not m:
        return None
    workload, p50, p99, mean, n = m.groups()
    validate_iterations(int(n))
    return f"{lang},{workload},{p50},{p99},{mean},{n}"


def format_csv_rows(outputs_by_lang: dict[str, list[str]]) -> list[str]:
    rows = [CSV_HEADER]
    for lang, lines in outputs_by_lang.items():
        for line in lines:
            parsed = parse_workload_line(lang, line)
            if parsed is not None:
                rows.append(parsed)
    return rows


def go_alphabet():
    return ", ".join(str(b) for b in ALPHABET)


def hy_alphabet():
    return ", ".join(str(b) for b in ALPHABET)


def render(tpl: str, windows: int = WINDOWS) -> str:
    validate_iterations(windows)
    validate_iterations(LOAD_ITEMS)
    validate_iterations(ALLOC_BATCHES)
    validate_iterations(ALLOC_BATCH)
    validate_iterations(ALLOC_ITEM)
    subs = {
        "@WINDOWS@": str(windows),
        "@LOAD_ITEMS@": str(LOAD_ITEMS),
        "@ALLOC_BATCHES@": str(ALLOC_BATCHES),
        "@ALLOC_BATCH@": str(ALLOC_BATCH),
        "@ALLOC_ITEM@": str(ALLOC_ITEM),
        "@ALPHABET_GO@": go_alphabet(),
        "@ALPHABET_RS@": ", ".join(str(b) + "u8" for b in ALPHABET),
        "@ALPHABET_HY@": hy_alphabet(),
    }
    out = tpl
    for k, v in subs.items():
        out = out.replace(k, v)
    return out


RUST_TOML = """[package]
name = "workloads"
version = "0.1.0"
edition = "2021"

[profile.release]
opt-level = 3
"""


def build_files(windows: int = WINDOWS) -> dict[str, str]:
    return {
        "go/main.go": render(GO_TEMPLATE, windows=windows),
        "rust/src/main.rs": render(RUST_TEMPLATE, windows=windows),
        "hy/load.hy": render(HY_LOAD_TEMPLATE, windows=windows),
        "hy/alloc.hy": render(HY_ALLOC_TEMPLATE, windows=windows),
        "rust/Cargo.toml": RUST_TOML,
    }


FILES = build_files(WINDOWS)


def run_self_test() -> int:
    fixture_path = ROOT / "tests" / "workload_cases.json"
    q_fixture = json.loads(fixture_path.read_text(encoding="utf-8"))
    c_fixture = q_fixture["csv_schema"]

    for case in q_fixture["cases"]:
        n, p, expected = case["n"], case["p"], case["expected_index"]
        got = quantile_index(n, p)
        if got != expected:
            raise AssertionError(f"quantile_index({n}, {p}) = {got}, expected {expected}")
        samples = list(range(1, n + 1))
        if pct_value(samples, p) != expected + 1:
            raise AssertionError(f"pct_value(1..{n}, {p}) != {expected + 1}")

    for bad_n in [*q_fixture["invalid_iterations"], True, False]:
        for fn in (
            lambda x=bad_n: validate_iterations(x),
            lambda x=bad_n: quantile_index(x, 99),
            lambda x=bad_n: render(GO_TEMPLATE, windows=x),
        ):
            try:
                fn()
            except ValueError:
                pass
            else:
                raise AssertionError(f"expected ValueError for iterations={bad_n!r}")

    for bad_p in [*q_fixture["invalid_percentiles"], True, False]:
        for fn in (
            lambda x=bad_p: quantile_index(100, x),
            lambda x=bad_p: pct_value([10, 20, 30], x),
        ):
            try:
                fn()
            except ValueError:
                pass
            else:
                raise AssertionError(f"expected ValueError for percentile={bad_p!r}")

    for fn in (
        lambda: pct_value([], 50),
        lambda: parse_workload_line("go", "alloc p50=120ns p99=240ns mean=135.5ns n=0"),
    ):
        try:
            fn()
        except ValueError:
            pass
        else:
            raise AssertionError("expected ValueError for empty samples / n=0 workload line")

    for bad_line in c_fixture["malformed_lines"]:
        if parse_workload_line("go", bad_line) is not None:
            raise AssertionError(f"expected None for malformed line {bad_line!r}")

    if "(p*n+99)/100 - 1" not in FILES["go/main.go"] or "p * len(sorted) / 100" in FILES["go/main.go"]:
        raise AssertionError("go/main.go missing nearest-rank formula")
    for rel in ("rust/src/main.rs", "hy/load.hy", "hy/alloc.hy"):
        src = FILES[rel]
        if "(p * n + 99) / 100 - 1" not in src:
            raise AssertionError(f"{rel} missing nearest-rank formula")
        if "p * len(sorted) / 100" in src or "p * sorted.len() / 100" in src:
            raise AssertionError(f"{rel} still contains legacy p * len / 100 formula")

    for rel, content in FILES.items():
        if "\r\n" in content:
            raise AssertionError(f"rendered {rel} contains CRLF")
        disk_path = ROOT / rel
        if disk_path.is_file() and b"\r\n" in disk_path.read_bytes():
            raise AssertionError(f"on-disk {rel} contains CRLF")

    for rel in ("hy/load.hy", "hy/alloc.hy"):
        for line in FILES[rel].splitlines():
            code = line.split("//", 1)[0]
            code = re.sub(r'"[^"]*"', '""', code)
            for ident in re.findall(r"\b[A-Za-z_][A-Za-z0-9_]*\b", code):
                if ident != ident.lower():
                    raise AssertionError(f"LX2 violation in {rel}: {ident}")

    if c_fixture["header"] != CSV_HEADER or c_fixture["columns"] != CSV_HEADER.split(","):
        raise AssertionError("CSV header/columns mismatch")
    noisy_outputs = {
        lang: [*c_fixture["malformed_lines"], *lines]
        for lang, lines in c_fixture["sample_outputs"].items()
    }
    rows = format_csv_rows(noisy_outputs)
    expected_rows = [c_fixture["header"], *c_fixture["expected_csv_rows"]]
    if rows != expected_rows:
        raise AssertionError(f"CSV rows mismatch: {rows} != {expected_rows}")

    run_sh = ROOT / "run.sh"
    if run_sh.is_file():
        sh_src = run_sh.read_text(encoding="utf-8")
        if CSV_HEADER not in sh_src:
            raise AssertionError(f"run.sh missing required CSV header: {CSV_HEADER}")

    print(
        f"self-test OK ({len(q_fixture['cases'])} quantile cases, "
        f"{len(q_fixture['invalid_iterations'])} invalid iteration checks, "
        f"{len(q_fixture['invalid_percentiles'])} invalid percentile checks, "
        f"{len(c_fixture['malformed_lines'])} malformed line checks, "
        f"{len(c_fixture['expected_csv_rows'])} CSV rows)"
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__.splitlines()[0], allow_abbrev=False,
    )
    parser.add_argument(
        "--check", action="store_true", help="verify generated files without writing",
    )
    parser.add_argument(
        "--self-test", action="store_true", help="verify quantile and CSV fixtures",
    )
    parser.add_argument(
        "--iterations", type=int, default=WINDOWS, help="window count (> 0)",
    )
    args = parser.parse_args()
    try:
        validate_iterations(args.iterations)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if args.self_test:
        return run_self_test()
    files = build_files(args.iterations)
    drift = []
    for rel, content in files.items():
        p = ROOT / rel
        if args.check:
            if not p.is_file() or p.read_text(encoding="utf-8") != content:
                drift.append(rel)
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {rel}")
    if args.check:
        if drift:
            print("DRIFTED (rerun `python3 shape.py` and commit):", ", ".join(drift))
            return 1
        print("triplet shapes in sync with shape.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())

